class DreamBoothDataset(Dataset):
    """
    A dataset to prepare the instance and class images with the prompts for fine-tuning the model.
    It pre-processes the images.
    """

    def __init__(
        self,
        instance_data_root,
        instance_prompt,
        class_prompt,
        class_data_root=None,
        class_num=None,
        size=1024,
        repeats=1,
        center_crop=False,
    ):
        self.size = size
        self.center_crop = center_crop

        self.instance_prompt = instance_prompt
        self.custom_instance_prompts = None
        self.class_prompt = class_prompt

        # if --dataset_name is provided or a metadata jsonl file is provided in the local --instance_data directory,
        # we load the training data using load_dataset


        self.instance_data_root = Path(instance_data_root)
        if not self.instance_data_root.exists():
            raise ValueError("Instance images root doesn't exists.")

        npy_files = sorted(self.instance_data_root.glob("*.npy"))
        if not npy_files:
            raise ValueError(f"No NPY files found in {self.instance_data_root}")

        self.instance_file_paths = []
        for path in npy_files:
            self.instance_file_paths.extend(itertools.repeat(path, repeats))

        self.num_instance_files = len(self.instance_file_paths)
        self._length = self.num_instance_files

        self.transform = transforms.Compose([
            transforms.Normalize([0.5], [0.5]),  # [0,1] -> [-1,1]
        ])

        self.custom_instance_prompts = None

        if class_data_root is not None:
            self.class_data_root = Path(class_data_root)
            self.class_data_root.mkdir(parents=True, exist_ok=True)
            self.class_file_paths = sorted(self.class_data_root.glob("*.npy"))

            if class_num is not None:
                self.num_class_files = min(len(self.class_file_paths), class_num)
            else:
                self.num_class_files = len(self.class_file_paths)

            self._length = max(self.num_class_files, self.num_instance_files)
        else:
            self.class_data_root = None

    def __len__(self):
        return self._length

    def __getitem__(self, index):
        example = {}
        file_path = self.instance_file_paths[index % self.num_instance_files]
        range_image = np.load(file_path)


        range_tensor = torch.from_numpy(range_image).float().unsqueeze(0)
        range_tensor = F.interpolate(range_tensor.unsqueeze(0), size=(256, 1024), mode='nearest')
        range_tensor = range_tensor.squeeze(0)
        range_tensor = range_tensor.repeat(3, 1, 1)

        range_tensor = self.transform(range_tensor)
        example["instance_images"] = range_tensor
        example["instance_prompt"] = self.instance_prompt
        

        if self.class_data_root:
            class_path = self.class_file_paths[index % self.num_class_files]
            class_image = np.load(class_path)
            class_tensor = torch.from_numpy(class_image).float().unsqueeze(0)
            class_tensor = self.transform(class_tensor)
            example["class_images"] = class_tensor
            example["class_prompt"] = self.class_prompt

        return example


